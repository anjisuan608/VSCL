// 图标生成器：scripts/icons.json（单一来源）→ 三份产物
//  1. media/icons.js          —— webview 内联用（fill="currentColor"，随 CSS 变量着色）
//  2. media/icons/light/*.svg —— QuickPick/TreeView light 主题（VS Code 图标不自动着色，需双套）
//  3. media/icons/dark/*.svg  —— QuickPick/TreeView dark 主题
// 由 npm precompile 钩子自动执行。
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const paths = JSON.parse(fs.readFileSync(path.join(root, "scripts", "icons.json"), "utf8"));

// ── 1. media/icons.js（webview 版，currentColor 主题自适应） ──
const js = `// <auto-generated> 由 scripts/gen-icons.mjs 从 scripts/icons.json 生成，勿手改。 </auto-generated>
(function () {
  var P = ${JSON.stringify(paths, null, 2)};
  function icon(name, size) {
    var d = P[name] || P.box;
    var s = size || 18;
    return '<svg viewBox="0 0 24 24" width="' + s + '" height="' + s + '" fill="currentColor" aria-hidden="true">' + d + "</svg>";
  }
  function renderIcons(root) {
    var nodes = (root || document).querySelectorAll("[data-icon]");
    for (var i = 0; i < nodes.length; i++) {
      var el = nodes[i];
      el.innerHTML = icon(el.getAttribute("data-icon"));
    }
  }
  window.VSCL_ICON = icon;
  window.VSCL_RENDER_ICONS = renderIcons;
})();
`;
fs.writeFileSync(path.join(root, "media", "icons.js"), js, "utf8");

// ── 2/3. light & dark 双主题 SVG 文件（QuickPick iconPath 用） ──
const THEMES = { light: "#616161", dark: "#CCCCCC" };
for (const [theme, color] of Object.entries(THEMES)) {
  const dir = path.join(root, "media", "icons", theme);
  fs.mkdirSync(dir, { recursive: true });
  for (const [name, d] of Object.entries(paths)) {
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="${color}">${d}</svg>\n`;
    fs.writeFileSync(path.join(dir, `${name}.svg`), svg, "utf8");
  }
}

console.log(`icons generated: ${Object.keys(paths).length} keys x {webview, light, dark}`);
